package ch.sbb.atlas.api.mail;

import static org.assertj.core.api.Assertions.assertThat;

import org.junit.jupiter.api.Test;

class MailTypeTest {

  @Test
  void shouldProvideSupportedMailTypes() {
    assertThat(MailType.values()).containsExactly(
        MailType.ATLAS_STANDARD,
        MailType.TU_IMPORT,
        MailType.SCHEDULING_ERROR_NOTIFICATION,
        MailType.UPDATE_GEOLOCATION_ERROR_NOTIFICATION,
        MailType.UPDATE_GEOLOCATION_SUCCESS_NOTIFICATION,
        MailType.EXPORT_SERVICE_POINT_ERROR_NOTIFICATION,
        MailType.LINE_STARTED_WORKFLOW_NOTIFICATION,
        MailType.LINE_APPROVED_WORKFLOW_NOTIFICATION,
        MailType.LINE_REJECTED_WORKFLOW_NOTIFICATION,
        MailType.START_STOP_POINT_WORKFLOW_EXAMINANT_NOTIFICATION,
        MailType.START_STOP_POINT_WORKFLOW_CC_NOTIFICATION,
        MailType.REJECT_STOP_POINT_WORKFLOW_NOTIFICATION,
        MailType.STOP_POINT_WORKFLOW_PINCODE_NOTIFICATION,
        MailType.APPROVED_STOP_POINT_WORKFLOW_NOTIFICATION,
        MailType.CANCEL_STOP_POINT_WORKFLOW_NOTIFICATION,
        MailType.STOP_POINT_WORKFLOW_RESTART_NOTIFICATION,
        MailType.STOP_POINT_WORKFLOW_RESTART_CC_NOTIFICATION,
        MailType.BULK_IMPORT_RESULT_NOTIFICATION,
        MailType.START_TERMINATION_STOP_POINT_WORKFLOW_NOTIFICATION,
        MailType.TARIFF_STOP_NOT_APPROVED_NOTIFICATION,
        MailType.TARIFF_STOP_APPROVED_NOTIFICATION,
        MailType.ABORT_TERMINATION_NOTIFICATION,
        MailType.STOP_POINT_TERMINATION_CONFIRMED_NOTIFICATION,
        MailType.TTH_DOSSIER_NEW_QUESTION_NOTIFICATION,
        MailType.TTH_DOSSIER_NEW_ANSWER_NOTIFICATION);
    assertThat(MailType.valueOf("ATLAS_STANDARD")).isEqualTo(MailType.ATLAS_STANDARD);
  }
}
